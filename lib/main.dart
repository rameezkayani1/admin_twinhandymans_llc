import 'package:admin_twinhandymans_llc/pages/login/login_page.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:get/get.dart';

import 'core/theme.dart';
import 'firebase_options.dart'; // generated by: flutterfire configure

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Signed-in owner/manager/crew -> Customers, anyone else -> Login
  final start = await LoginController.startPage();
  runApp(AdminApp(start: start));
}

class AdminApp extends StatelessWidget {
  final Widget start;
  const AdminApp({super.key, required this.start});

  @override
  Widget build(BuildContext context) {
    return GetMaterialApp(
      title: 'Twins Handyman Admin',
      debugShowCheckedModeBanner: false,
      theme: buildTheme(),
      home: start,
    );
  }
}
